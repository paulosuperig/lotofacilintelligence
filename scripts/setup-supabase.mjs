#!/usr/bin/env node
/**
 * setup-supabase.mjs
 * Contract: Generates or updates the .env file with Supabase public credentials.
 * 
 * Inputs:
 *   - Environment Variables: SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY (or SUPABASE_ANON_KEY), SUPABASE_PROJECT_ID
 *   - CLI Flags: --url, --key, --project, --force
 * 
 * Outputs:
 *   - .env file
 *   - .env.bak (if .env existed)
 *   - Exit code 0 on success, 1 on invalid credentials.
 */
import { writeFileSync, existsSync, readFileSync, copyFileSync } from 'node:fs';
import { resolve } from 'node:path';

const DEFAULTS = {
  SUPABASE_URL: 'https://wevgcjgutpdazhqkhzhm.supabase.co',
  SUPABASE_PROJECT_ID: 'wevgcjgutpdazhqkhzhm',
  SUPABASE_PUBLISHABLE_KEY:
    'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6Indldmdjamd1dHBkYXpocWtoemhtIiwicm9sZSI6ImFub24iLCJpYXQiOjE3Nzg4NTU4MTgsImV4cCI6MjA5NDQzMTgxOH0.QoPHF68n_-aU27f5HsmysQbMpuI4XxJ0HABE8Chjbtk',
};

const flags = Object.fromEntries(
  process.argv.slice(2)
    .filter((a) => a.startsWith('--'))
    .map((a) => {
      const [k, ...rest] = a.replace(/^--/, '').split('=');
      return [k.toLowerCase(), rest.join('=')];
    })
);

const url = flags.url || process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || DEFAULTS.SUPABASE_URL;
const key = flags.key || process.env.SUPABASE_PUBLISHABLE_KEY || process.env.SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_PUBLISHABLE_KEY || DEFAULTS.SUPABASE_PUBLISHABLE_KEY;
const projectId = flags.project || process.env.SUPABASE_PROJECT_ID || process.env.VITE_SUPABASE_PROJECT_ID || DEFAULTS.SUPABASE_PROJECT_ID;

if (!url?.startsWith('http') || !key || !projectId) {
  console.error('❌ Error: Invalid credentials. Provide --url, --key, and --project or set environment variables.');
  process.exit(1);
}

const envPath = resolve(process.cwd(), '.env');
if (existsSync(envPath) && !flags.force) {
  copyFileSync(envPath, envPath + '.bak');
  console.log('📦 Backup created at .env.bak');
}

const content =
  `# Generated by scripts/setup-supabase.mjs\n` +
  `VITE_SUPABASE_PROJECT_ID="${projectId}"\n` +
  `VITE_SUPABASE_PUBLISHABLE_KEY="${key}"\n` +
  `VITE_SUPABASE_URL="${url}"\n`;

try {
  writeFileSync(envPath, content, 'utf8');
  console.log('✅ .env file updated successfully:');
  console.log(`   • URL: ${url}`);
  console.log(`   • Project ID: ${projectId}`);
  console.log(`   • Key: ${key.slice(0, 10)}...${key.slice(-10)}`);
} catch (error) {
  console.error(`❌ Failed to write .env file: ${error.message}`);
  process.exit(1);
}
